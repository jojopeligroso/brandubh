const [fromName, toName] = token.replace(/x.*$/, "").split("-");
check(
  (await mb.locator(`[data-point="${toName}"]`).getAttribute("aria-label")) === `${toName} black`,
  `the engine's stone landed on ${toName}`,
);
check(
  await mb.locator(`[data-point="${toName}"] .morris-stone.is-black`).isVisible(),
  "the landed stone is shown rather than left hidden under a copy that is gone",
);
check(
  (await mb.locator(`[data-point="${fromName}"] .morris-origin`).count()) === 1,
  `the point it came from is left lit (${fromName})`,
);

