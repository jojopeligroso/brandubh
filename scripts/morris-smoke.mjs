// Driven-browser assertions for the Nine Men's Morris surface.
//   npm run check:morris
//
// Sits beside tablut-smoke.mjs and copenhagen-smoke.mjs and copies their harness
// verbatim — server, browser discovery, init-script seeding — for the fourth
// time (ADR-0008 counts that as one of the costs of a fourth board). The reason
// it exists is the same and the things it can catch are not: the test suites are
// pure logic, so nothing in them can fail when a board made of points draws
// wrong.
//
// What can only break here:
//
//   • the board is **24 point targets**, named `a7 … a1` with `d7` at the top
//     middle. A square-lattice board that drew 49 cells, or a points table that
//     drifted from the indexing in game/morris/rules.ts, would look like a
//     plausible board and fail nothing in the suites;
//   • closing a mill enters a **removal step** that rings only the stones the
//     rules allow taking, ignores every other click, and completes the turn on
//     the removal. `removable()` has its own unit tests; whether the *board* lit
//     those stones is invisible to them;
//   • the engine's reply is *shown* on the point it went to — one worker, one
//     reply, one stone, in a real browser;
//   • Ballinderry is **KEPT** on this surface, with the stored choice untouched,
//     and the board draws 24 drilled holes under it. This is the exact inverse of
//     the assertion in tablut-smoke.mjs and copenhagen-smoke.mjs, and it is the
//     whole reason this check is worth its runtime: `morris.surface.v1` is
//     deliberately absent from index.html's hand-written fallback list, so that
//     list is no longer "the surfaces" but "the surfaces that fall Ballinderry
//     back" — and nothing at that call site says so (ADR-0008);
//   • a Morris game survives leaving the surface, coming back, and a full reload;
//   • the Brandubh save is byte-identical after the visit, and the game did not
//     land in another board's key;
//   • three-way mutual exclusion: opening any board closes the other two.
//
// Same Chromium discovery list as screenshot.mjs and the other smoke scripts;
// keep them in step.
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { extname, join, normalize } from "node:path";
import { chromium } from "playwright-core";

const DIST = new URL("../dist/", import.meta.url).pathname;
// playwright-core ships no browser of its own, so it always needs an explicit
// executable. Prefer CHROMIUM_PATH, then the sandbox's pre-provisioned build,
// then whatever the distro installed.
const CANDIDATES = [
  process.env.CHROMIUM_PATH,
  "/opt/pw-browsers/chromium-1194/chrome-linux/chrome",
  "/usr/bin/chromium",
  "/usr/bin/chromium-browser",
  "/usr/bin/google-chrome-stable",
].filter(Boolean);
const CHROME = CANDIDATES.find((p) => existsSync(p));
if (!CHROME) {
  console.error("no Chromium found; set CHROMIUM_PATH. Tried:\n  " + CANDIDATES.join("\n  "));
  process.exit(2);
}
const MIME = {
  ".html": "text/html",
  ".js": "text/javascript",
  ".css": "text/css",
  ".otf": "font/otf",
  ".png": "image/png",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".gz": "application/gzip",
  ".bin": "application/octet-stream",
};

const server = createServer(async (req, res) => {
  try {
    let path = decodeURIComponent(new URL(req.url, "http://x").pathname);
    if (path === "/") path = "/index.html";
    const file = normalize(join(DIST, path));
    if (!file.startsWith(DIST)) throw new Error("escape");
    const body = await readFile(file);
    res.writeHead(200, { "content-type": MIME[extname(file)] ?? "application/octet-stream" });
    res.end(body);
  } catch {
    // SPA fallback: serve index.html for unknown routes.
    try {
      res.writeHead(200, { "content-type": "text/html" });
      res.end(await readFile(join(DIST, "index.html")));
    } catch {
      res.writeHead(404);
      res.end();
    }
  }
});

await new Promise((r) => server.listen(0, r));
const { port } = server.address();

