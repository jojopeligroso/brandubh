const stepDots = await mb.locator(".morris-dot").count();
check(stepDots === 2, "a selected stone offers exactly its two empty neighbours", `saw ${stepDots}`);
// The flight has to be watched for *before* the move that provokes it: the
// engine answers this position in a moment and the stone is only in the air for
// half a second, so a check that starts after the reply has landed can never see
// it. `waitForFunction` polls on animation frames, which is fast enough.
const inFlight = page
  .waitForFunction(
    () =>
      document.querySelector(".morris-mover") !== null &&
      document.querySelector(".morris-stone.in-flight") !== null,
    undefined,
    { timeout: 60000 },
  )
  .then(() => true)
  .catch(() => false);
await mb.locator('[data-point="d5"]').click();
check(
  (await mb.locator('[data-point="d5"][aria-label="d5 white"]').count()) === 1,
  "a step along a line is played by click, then click",
);
check(await inFlight, "the engine's stone travels: a copy in flight, the real one waiting under it");
// Caught mid-flight, the copy is drawn *away* from the point the move went to —
// which is the whole difference between a stone that travels and a stone that
// teleports with a decoration beside it. The transition returns it to the
// identity transform, i.e. to its destination, and it is taken down there.
const travelled = await page.evaluate(() => {
  const mover = document.querySelector(".morris-mover");
  return mover ? getComputedStyle(mover).transform : "gone";
});
const offset = /matrix\(1, 0, 0, 1, (-?[\d.]+), (-?[\d.]+)\)/.exec(travelled);
check(
  !!offset && (Number(offset[1]) !== 0 || Number(offset[2]) !== 0),
  "…and while it travels it is drawn away from the point it is going to",
  travelled,
);

// Then it lands: the copy comes down, the real stone shows on the point the move
