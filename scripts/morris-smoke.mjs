// ── The moving phase: a step, and the engine's stone *travelling* ─────────────
// Seeded rather than played: eighteen placements is eighteen clicks and a lot of
// engine waiting, and what this section is for is the one thing that only exists
// once both hands are empty — a stone that *moves*. The save is a mill-free
// placing phase (generated from the engine's own move list, so every ply is
// legal by construction), with White to play and exactly two moves available.
//
// The travel is worth a driven-browser check for the same reason
// `npm run check:ai-reveal` exists for the square boards: a copy of the stone
// that renders but never translates, or a real stone that appears on its point
// immediately with a decoration flying in beside it, look identical to a correct
// reveal in any screenshot and fail nothing in the suites. (The second of those
// was a real bug in this board's first cut.)
await page.evaluate((moves) => {
  const now = Date.now();
  localStorage.setItem("morris.surface.v1", "1");
  localStorage.setItem(
    "morris.game.v1",
    JSON.stringify({
      v: 1,
      id: "moving-phase",
      createdAt: now,
      savedAt: now,
      variantId: "morris-gasser-1",
      customRules: {},
      playMode: "white",
      difficulty: "medium",
      moves,
      status: "playing",
      cursor: moves.length,
      recorded: false,
      clock: null,
      match: null,
      gamesPerSet: 1,
      names: { p1: "", p2: "" },
    }),
  );
}, MOVING_PHASE_MOVES);
await page.reload({ waitUntil: "networkidle" });
await mb.waitFor();
check(
  (await page.locator(".morris-dot").count()) === 0,
  "nothing is offered until a stone is picked up in the moving phase",
);
